#!/usr/bin/env node

/**
 * install-launcher.mjs — make Frontrunner something you can double-click.
 *
 * `npm start` is a better day-two story than `npm run ui`, but it is still a
 * command typed into a terminal by someone who was never meant to need one.
 * This writes a small launcher for the host platform that starts the same
 * thing, so opening Frontrunner is an icon rather than a recalled incantation.
 *
 * Written into `workspace/` because it is generated content on this machine,
 * and generated content is exactly what `workspace/` is for. Nothing is
 * installed system-wide, no login item is registered, and nothing outside the
 * project is touched — the user drags the launcher wherever they want it,
 * which keeps the decision, and the mess, theirs.
 *
 * The launcher is a thin shim: it changes into the project and runs
 * `node src/application/start.mjs`. All the real behaviour stays in one place,
 * so a launcher generated today keeps working after an update changes how
 * starting works.
 */

import { chmodSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

import { ROOT, WORKSPACE_DIR } from '#paths';
import { replaceFileAtomic } from '../lib/locked-file.mjs';

/**
 * Quote a path for the shell that will run it.
 *
 * The project path is chosen by whoever cloned the repository and routinely
 * contains spaces on macOS ("Google Drive", "My Documents"). Single quotes with
 * escaped single quotes is the only form that survives every practical case;
 * for cmd, quoting is enough because `cd /d` takes one quoted argument.
 */
export function shellQuote(value) {
  return `'${String(value).replaceAll("'", `'\\''`)}'`;
}

export function launcherFor(platform, root) {
  if (platform === 'win32') {
    return {
      name: 'Frontrunner.cmd',
      mode: 0o644,
      contents: [
        '@echo off',
        'title Frontrunner',
        `cd /d "${root}"`,
        'node src\\application\\start.mjs',
        'if errorlevel 1 pause',
        '',
      ].join('\r\n'),
    };
  }
  // .command is the macOS extension Finder opens in Terminal on a double
  // click. Linux desktops do not honour it, but they do run an executable
  // shell script, so one file serves both.
  return {
    name: platform === 'darwin' ? 'Frontrunner.command' : 'Frontrunner.sh',
    mode: 0o755,
    contents: [
      '#!/bin/sh',
      '# Generated by Frontrunner. Safe to move, copy, or delete.',
      `cd ${shellQuote(root)} || exit 1`,
      'exec node src/application/start.mjs',
      '',
    ].join('\n'),
  };
}

export function installLauncher({ platform = process.platform, root = ROOT, dir = WORKSPACE_DIR } = {}) {
  const launcher = launcherFor(platform, root);
  mkdirSync(dir, { recursive: true });
  const file = join(dir, launcher.name);
  replaceFileAtomic(file, launcher.contents, { mode: launcher.mode });
  // replaceFileAtomic writes through a temp file, so the mode is reapplied
  // here rather than assumed: an executable bit that silently did not survive
  // the rename produces a launcher that does nothing when double-clicked.
  chmodSync(file, launcher.mode);
  return file;
}

export function main({ log = console.log, platform = process.platform } = {}) {
  const file = installLauncher({ platform });
  log(`Created ${file}`);
  if (platform === 'darwin') {
    log('Double-click it to start Frontrunner. Drag it to your Dock or Desktop to keep it handy.');
    log('The first time, macOS may ask you to confirm — choose Open.');
  } else if (platform === 'win32') {
    log('Double-click it to start Frontrunner. Right-click it and Send to > Desktop to keep it handy.');
  } else {
    log('Run it to start Frontrunner, or add it to your desktop launcher.');
  }
  return file;
}

const direct = process.argv[1]
  && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (direct) {
  try {
    main();
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
